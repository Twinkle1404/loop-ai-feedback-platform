import React from 'react'
import Link from 'next/link'
import { Card } from '@/components/ui/Card'
import { FileText, Calendar, ArrowRight, User } from 'lucide-react'

export interface ReportItem {
  id: string
  title: string
  periodStart: string
  periodEnd: string
  createdAt: string
  generatedBy?: {
    name: string | null
    email: string
  } | null
  contentJson?: {
    stats?: {
      totalItems?: number
      percentNegative?: number
    }
  }
}

export function ReportCard({ report }: { report: ReportItem }) {
  const dtCreated = new Date(report.createdAt)
  const dtStart = new Date(report.periodStart)
  const dtEnd = new Date(report.periodEnd)

  const formattedPeriod = `${!isNaN(dtStart.getTime()) ? dtStart.toLocaleDateString(undefined, { month: 'short', day: 'numeric', year: 'numeric' }) : report.periodStart} – ${!isNaN(dtEnd.getTime()) ? dtEnd.toLocaleDateString(undefined, { month: 'short', day: 'numeric', year: 'numeric' }) : report.periodEnd}`
  const formattedCreated = !isNaN(dtCreated.getTime()) ? dtCreated.toLocaleDateString(undefined, { month: 'short', day: 'numeric' }) : ''

  return (
    <Card className="p-4 sm:p-5 hover:border-indigo-200 dark:hover:border-indigo-900/50 transition-all hover:shadow-md">
      <div className="flex items-start justify-between gap-3 sm:gap-4">
        <div className="flex items-start gap-3 sm:gap-3.5 min-w-0">
          <div className="p-2.5 sm:p-3 rounded-2xl bg-indigo-50 dark:bg-indigo-950/60 text-indigo-600 dark:text-indigo-400 shrink-0">
            <FileText className="w-4 h-4 sm:w-5 sm:h-5" />
          </div>
          <div className="min-w-0">
            <h3 className="font-bold text-sm sm:text-base text-zinc-900 dark:text-zinc-100 truncate">
              {report.title}
            </h3>
            <div className="flex items-center gap-1.5 sm:gap-2 mt-1 text-xs text-zinc-500">
              <Calendar className="w-3.5 h-3.5 shrink-0" />
              <span className="truncate">{formattedPeriod}</span>
            </div>
          </div>
        </div>

        <Link
          href={`/reports/${report.id}`}
          className="p-2 rounded-xl bg-zinc-100 hover:bg-indigo-600 hover:text-white dark:bg-zinc-800 text-zinc-600 dark:text-zinc-300 transition-colors shrink-0"
        >
          <ArrowRight className="w-4 h-4" />
        </Link>
      </div>

      <div className="mt-4 pt-3 sm:pt-4 border-t border-zinc-100 dark:border-zinc-800 flex flex-col sm:flex-row sm:items-center justify-between gap-1 text-[11px] sm:text-xs text-zinc-400">
        <div className="flex items-center gap-1.5 truncate">
          <User className="w-3.5 h-3.5 shrink-0" />
          <span className="truncate">Generated by {report.generatedBy?.name || report.generatedBy?.email || 'Admin'}</span>
        </div>
        <span className="shrink-0">{formattedCreated}</span>
      </div>
    </Card>
  )
}
